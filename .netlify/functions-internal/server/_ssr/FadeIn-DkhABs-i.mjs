function useProduct(slug) {
  return useQuery({
    queryKey: ["product", slug],
    queryFn: async () => {
      const { data: product, error } = await supabase.from("products").select("*").eq("product_slug", slug).maybeSingle();
      if (error) throw new Error(error.message);
      if (!product) return null;
      const { data: images } = await supabase.from("product_images").select("*").eq("product_id", product.id).order("image_order", { ascending: true });
      return {
        product,
        images: images ?? []
      };
    }
  });
}
